"""Compare auto and large-only Test Lab runs and write measured Markdown results."""

import argparse
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import httpx


def _limit(value: str) -> int:
    """Restrict a benchmark prefix to the built-in suite's 40 prompts."""
    try:
        limit = int(value)
    except ValueError as error:
        raise argparse.ArgumentTypeError("Limit must be an integer from 1 to 40.") from error
    if not 1 <= limit <= 40:
        raise argparse.ArgumentTypeError("Limit must be an integer from 1 to 40.")
    return limit


def run_benchmark(client: httpx.Client, limit: int | None = None) -> list[dict[str, Any]]:
    """Run the same default suite through the API in auto and forced-large modes."""
    runs = []
    for mode in ("auto", "large"):
        payload: dict[str, Any] = {"suite": "default", "mode": mode}
        if limit is not None:
            payload["limit"] = limit
        print(f"Running {mode}...", flush=True)
        response = client.post("v1/testlab/run", json=payload)
        response.raise_for_status()
        runs.append(response.json())
    if [result["id"] for result in runs[0]["results"]] != [result["id"] for result in runs[1]["results"]]:
        raise ValueError("The two benchmark runs did not use the same prompt IDs.")
    return runs


def format_report(runs: list[dict[str, Any]], limit: int | None = None) -> str:
    """Render measured routing/cost summaries with explicit scope and metric caveats."""
    scope = "full default suite" if limit is None else f"first {limit} prompts of the default suite"
    lines = [
        "<!-- Measured Test Lab results generated by scripts/benchmark.py. -->",
        "# SmartRoute Benchmark", "",
        f"Generated at: {datetime.now(timezone.utc).isoformat()}",
        f"Scope: {scope}. Prompts per mode: {runs[0]['prompt_count']}.", "",
        "| Mode | Routing Match | Escalation | Avg Latency (ms) | Actual USD | Reference USD | Saved | Final Tiers |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for run in runs:
        summary = run["summary"]
        distribution = Counter(result["tier_final"] for result in run["results"])
        tiers = ", ".join(f"{tier}: {count}" for tier, count in sorted(distribution.items()))
        lines.append(
            f"| {run['mode']} | {summary['routing_accuracy']:.1%} | {summary['escalation_rate']:.1%} "
            f"| {summary['avg_latency_ms']:.1f} | {summary['total_actual_usd']:.6f} "
            f"| {summary['total_reference_usd']:.6f} | {summary['saved_pct']:.1f}% | {tiers} |"
        )
    lines.extend([
        "", "Routing match is final tier == expected tier, not answer correctness.",
        "When large is disabled, large-only resolves to medium; final-tier counts show the models' tiers actually used.",
        "Savings compare configured actual costs with a hypothetical premium reference, not a paid-model quality benchmark.",
        "Both modes use the Test Lab's 256-token answer limit and the current gateway configuration.", "",
    ])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    """Run the benchmark CLI and write a report only after both modes complete."""
    parser = argparse.ArgumentParser(description="Compare SmartRoute auto and large-only routing.")
    parser.add_argument("--base-url", default="http://localhost:8000", help="Gateway root URL, without /v1.")
    parser.add_argument("--limit", type=_limit, help="Run only the first N prompts in each mode (1-40).")
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("benchmark_results.md"))
    args = parser.parse_args(argv)
    try:
        with httpx.Client(
            base_url=args.base_url.rstrip("/") + "/", timeout=httpx.Timeout(None, connect=10.0)
        ) as client:
            runs = run_benchmark(client, args.limit)
        report = format_report(runs, args.limit)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(report, encoding="utf-8")
    except (httpx.HTTPError, OSError, ValueError) as error:
        raise SystemExit(f"Benchmark failed: {error}") from error
    print(report)
    print(f"Report written to {args.output}")


if __name__ == "__main__":
    main()